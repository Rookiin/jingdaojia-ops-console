/**
 * 把 Web 端共享内核同步到小程序目录，并生成演示数据包与哈希清单。
 *
 * 用法：npm run sync:mp
 * 说明：小程序根目录不能 import 仓库根之外的代码，因此这里做「复制 + 哈希校验」，
 * 保证两端共用同一份业务规则；改动源文件后必须重新执行本脚本。
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { buildFieldTasks } from '../src/data/field-tasks.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const MP_DIR = join(ROOT, 'miniprogram')
const CORE_DIR = join(MP_DIR, 'core')
const DATA_DIR = join(MP_DIR, 'data')

/** 源文件 → 小程序 core 目标文件名（扁平目录，相对 import 与源一致） */
const CORE_FILES = {
  'src/domain/types.js': 'types.js',
  'src/domain/money.js': 'money.js',
  'src/domain/period.js': 'period.js',
  'src/lib/id.js': 'id.js',
  'src/shared/geo.js': 'geo.js',
  'src/shared/field-actions.js': 'field-actions.js',
}

const GENERATED_HEADER =
  '/* AUTO-GENERATED by scripts/sync-miniprogram.mjs from {source} — 请勿手工修改，改动请改源文件后重新执行 npm run sync:mp */\n\n'

function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex')
}

function readSource(relPath) {
  return readFileSync(join(ROOT, relPath), 'utf8')
}

function main() {
  rmSync(CORE_DIR, { recursive: true, force: true })
  mkdirSync(CORE_DIR, { recursive: true })
  mkdirSync(DATA_DIR, { recursive: true })

  const files = {}
  const sources = {}

  for (const [source, target] of Object.entries(CORE_FILES)) {
    const raw = readSource(source)
    sources[source] = sha256(raw)
    const content = GENERATED_HEADER.replace('{source}', source) + raw
    writeFileSync(join(CORE_DIR, target), content, 'utf8')
    files[`core/${target}`] = sha256(content)
  }

  const bundle = buildFieldTasks()
  const seedJson = `${JSON.stringify(bundle, null, 2)}\n`
  writeFileSync(join(DATA_DIR, 'seed.json'), seedJson, 'utf8')
  files['data/seed.json'] = sha256(seedJson)

  // 小程序运行时不依赖 JSON loader，同时提供 ESM 版本供 import
  const seedModule =
    '/* AUTO-GENERATED by scripts/sync-miniprogram.mjs — 请勿手工修改 */\n' +
    `export default ${JSON.stringify(bundle, null, 2)}\n`
  writeFileSync(join(DATA_DIR, 'seed.js'), seedModule, 'utf8')
  files['data/seed.js'] = sha256(seedModule)

  const manifest = {
    generator: 'scripts/sync-miniprogram.mjs',
    seedId: bundle.seedId,
    seedGeneratedAt: bundle.generatedAt,
    coreFiles: Object.values(CORE_FILES),
    sources,
    files,
  }
  writeFileSync(
    join(MP_DIR, 'MANIFEST.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  )

  const total = Object.keys(files).length
  console.log(`[sync:mp] 已生成 ${total} 个文件到 ${relative(ROOT, MP_DIR)}`)
  console.log(`[sync:mp] 任务 ${bundle.tasks.length} 张 / 阿姨 ${bundle.cleaners.length} 位 / 客户 ${bundle.customers.length} 位`)
  console.log(`[sync:mp] 数据包大小 ${Buffer.byteLength(seedJson, 'utf8')} 字节`)
}

main()
